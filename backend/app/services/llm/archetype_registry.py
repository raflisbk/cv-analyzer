for _domain, _entries in _EXPANSIONS.items():
    if _domain in REGISTRY:
        REGISTRY[_domain]["archetypes"].update(_entries)


def get_domain_list() -> str:
    """Formatted domain list for tier-1 LLM prompt."""
    return "\n".join(f"{key}: {data['display_name']}" for key, data in REGISTRY.items())


def get_archetype_keys(domain: str) -> list[str]:
    return list(REGISTRY.get(domain, {}).get("archetypes", {}).keys())


def get_archetype_list(domain: str) -> str:
    """Comma-separated archetype keys for tier-2 LLM prompt."""
    return ", ".join(get_archetype_keys(domain))


def get_description(domain: str, archetype: str) -> str:
    return REGISTRY.get(domain, {}).get("archetypes", {}).get(archetype, "")


def get_display_name(key: str) -> str:
    """Human-readable archetype name from snake_case key."""
    return key.replace("_", " ").title()


def total_archetypes() -> int:
    return sum(len(d["archetypes"]) for d in REGISTRY.values())
